"""Fit the detector, pick thresholds on validation, report precision and recall on a later test period.

Split is by time: days 0-53 train, 54-71 validation, 72-89 test. The test period is never used to
fit the model or choose thresholds.

Usage:  python -m anomaly.train
"""

from __future__ import annotations

import json
import time
from datetime import UTC, datetime

import numpy as np
import pandas as pd

from anomaly.config import DATA_FILE, METRICS_FILE, MODEL_VERSION
from anomaly.detector import Detector
from anomaly.features import build_features
from anomaly.generate import START, generate

TRAIN_DAYS, VAL_DAYS = 54, 18
HOLD_PRECISION_TARGET = 0.95
RECALL_TARGET = 0.80


def split(feats: pd.DataFrame):
    day = (feats["timestamp"] - pd.Timestamp(START)).dt.days
    return (feats[day < TRAIN_DAYS], feats[(day >= TRAIN_DAYS) & (day < TRAIN_DAYS + VAL_DAYS)],
            feats[day >= TRAIN_DAYS + VAL_DAYS])


def prf(flagged: np.ndarray, y: np.ndarray) -> dict:
    tp = int((flagged & (y == 1)).sum())
    fp = int((flagged & (y == 0)).sum())
    fn = int((~flagged & (y == 1)).sum())
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    return {"precision": round(p, 4), "recall": round(r, 4), "f1": round(f1, 4),
            "true_positives": tp, "false_positives": fp, "false_negatives": fn,
            "false_positives_per_1000_normal": round(1000 * fp / max(1, int((y == 0).sum())), 2)}


def best_f1_threshold(score: np.ndarray, y: np.ndarray) -> float:
    candidates = np.unique(np.quantile(score, np.linspace(0.80, 0.9999, 600)))
    f1s = [prf(score >= t, y)["f1"] for t in candidates]
    return float(candidates[int(np.argmax(f1s))])


def recall_threshold(score: np.ndarray, y: np.ndarray, target: float) -> float:
    """Highest threshold that still flags at least `target` of the anomalies."""
    pos = np.sort(score[y == 1])[::-1]
    k = int(np.ceil(target * len(pos))) - 1
    return float(pos[max(k, 0)])


def hold_threshold(score: np.ndarray, y: np.ndarray, start: float, min_cases: int = 20) -> float:
    for t in np.unique(score[score >= start]):
        sel = score >= t
        if sel.sum() < min_cases:
            break
        if y[sel].mean() >= HOLD_PRECISION_TARGET:
            return float(t)
    return 1.01


def lanes(score, y, flag_t, hold_t) -> dict:
    out = {}
    for name, mask in (("hold", score >= hold_t), ("review_queue", (score >= flag_t) & (score < hold_t))):
        n = int(mask.sum())
        out[name] = {"transactions": n, "precision": round(float(y[mask].mean()), 4) if n else None,
                     "share_of_true_anomalies": round(float((mask & (y == 1)).sum() / max(1, (y == 1).sum())), 4)}
    return out


def main() -> None:
    started = time.time()
    df = pd.read_csv(DATA_FILE) if DATA_FILE.exists() else generate()
    feats = build_features(df)
    train, val, test = split(feats)

    det = Detector.fit(train)
    det.calibrate(val)
    v_score, v_model, _, _ = det.combined(val)
    yv = val["is_anomaly"].to_numpy()
    det.flag_threshold = recall_threshold(v_score, yv, RECALL_TARGET)
    det.hold_threshold = hold_threshold(v_score, yv, det.flag_threshold)
    model_only_t = best_f1_threshold(v_model, yv)

    t_score, t_model, t_rule, _ = det.combined(test)
    yt = test["is_anomaly"].to_numpy()
    flagged = t_score >= det.flag_threshold

    by_type = {}
    for kind, g in test[test.is_anomaly == 1].groupby("anomaly_type"):
        idx = test.index.get_indexer(g.index)
        by_type[kind] = {"transactions": len(g), "recall": round(float(flagged[idx].mean()), 4)}

    metrics = {
        "model_version": MODEL_VERSION,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "data": {
            "source": "synthetic, generated by anomaly/generate.py (seed 7)",
            "transactions": len(df), "customers": int(df.customer_id.nunique()),
            "anomaly_rate": round(float(df.is_anomaly.mean()), 4),
            "split": {"train": len(train), "validation": len(val), "test": len(test)},
            "test_anomalies": int(yt.sum()),
        },
        "thresholds": {"flag": round(det.flag_threshold, 4), "hold": round(det.hold_threshold, 4),
                       "picked_on": "validation period (calibration also fit on validation)",
                       "rule_precision_on_validation": det.rule_precision,
                       "flag_rule": f"highest score that still flags {RECALL_TARGET:.0%} of validation anomalies",
                       "hold_rule": f"lowest score with >= {HOLD_PRECISION_TARGET:.0%} precision on validation"},
        "test": {
            "combined": prf(flagged, yt),
            "rules_only": prf(t_rule, yt),
            "model_only": prf(t_model >= model_only_t, yt),
            "recall_by_anomaly_type": by_type,
            "lanes": lanes(t_score, yt, det.flag_threshold, det.hold_threshold),
        },
        "validation": {"combined": prf(v_score >= det.flag_threshold, yv)},
        "wall_clock_seconds": round(time.time() - started, 1),
    }
    det.save()
    METRICS_FILE.write_text(json.dumps(metrics, indent=2) + "\n")
    print(json.dumps({k: metrics[k] for k in ("thresholds", "test")}, indent=2))


if __name__ == "__main__":
    main()
